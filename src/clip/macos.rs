//! macOS clipboard. NSPasteboard has no change notification, so we poll
//! its change count (cheap) a few times a second.
#![allow(unused_unsafe)]

use std::sync::atomic::{AtomicIsize, Ordering};
use std::sync::mpsc::Sender;
use std::sync::Arc;
use std::time::Duration;

use anyhow::{bail, Result};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
};
use objc2_foundation::{NSData, NSString};

use super::{ClipEvent, Clipboard};
use crate::content::{to_png, Content};

/// Markers from nspasteboard.org that password managers set.
const SECRET_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

fn read(pb: &NSPasteboard) -> Option<ClipEvent> {
    unsafe {
        let types: Vec<String> = pb
            .types()
            .map(|t| t.iter().map(|s| s.to_string()).collect())
            .unwrap_or_default();
        let sensitive = types.iter().any(|t| SECRET_TYPES.contains(&t.as_str()));
        let content = if let Some(s) = pb.stringForType(NSPasteboardTypeString) {
            Content::Text(s.to_string())
        } else if let Some(d) = pb.dataForType(NSPasteboardTypePNG) {
            Content::Image(d.to_vec())
        } else {
            Content::Image(to_png(&pb.dataForType(NSPasteboardTypeTIFF)?.to_vec())?)
        };
        Some(ClipEvent { content, sensitive })
    }
}

struct MacClipboard {
    /// Change count right after our own last write, so the poller skips it.
    own: Arc<AtomicIsize>,
}

impl Clipboard for MacClipboard {
    fn write(&self, c: &Content, transient: bool) -> Result<()> {
        unsafe {
            let pb = NSPasteboard::generalPasteboard();
            pb.clearContents();
            let ok = match c {
                Content::Text(s) => {
                    pb.setString_forType(&NSString::from_str(s), NSPasteboardTypeString)
                }
                Content::Image(png) => {
                    pb.setData_forType(Some(&NSData::with_bytes(png)), NSPasteboardTypePNG)
                }
            };
            if transient {
                let t = NSString::from_str("org.nspasteboard.TransientType");
                pb.setData_forType(Some(&NSData::new()), &t);
            }
            self.own.store(pb.changeCount(), Ordering::SeqCst);
            if !ok {
                bail!("could not write to the pasteboard");
            }
        }
        Ok(())
    }

    fn name(&self) -> &'static str {
        "macos"
    }
}

pub fn start(tx: Sender<ClipEvent>) -> Result<Arc<dyn Clipboard>> {
    let own = Arc::new(AtomicIsize::new(-1));
    let own_poll = own.clone();
    std::thread::Builder::new()
        .name("pasteboard".into())
        .spawn(move || {
            let mut last: isize = -1;
            loop {
                let ev = unsafe {
                    let pb = NSPasteboard::generalPasteboard();
                    let count = pb.changeCount();
                    if count == last {
                        None
                    } else {
                        last = count;
                        if count == own_poll.load(Ordering::SeqCst) {
                            None
                        } else {
                            read(&pb)
                        }
                    }
                };
                if let Some(ev) = ev {
                    if tx.send(ev).is_err() {
                        return;
                    }
                }
                std::thread::sleep(Duration::from_millis(250));
            }
        })?;
    Ok(Arc::new(MacClipboard { own }))
}
